package com.dentacloud.app.ui.billing;

import android.content.Context;

import androidx.lifecycle.LiveData;
import androidx.lifecycle.MutableLiveData;
import androidx.lifecycle.ViewModel;

import com.dentacloud.app.data.local.SessionStore;
import com.dentacloud.app.data.local.entity.InvoiceEntity;
import com.dentacloud.app.data.local.entity.InvoiceLineEntity;
import com.dentacloud.app.data.local.entity.PatientEntity;
import com.dentacloud.app.data.local.entity.PaymentEntryEntity;
import com.dentacloud.app.data.repo.BillingRepository;
import com.dentacloud.app.data.repo.PatientRepository;
import com.dentacloud.app.util.Dates;
import com.dentacloud.app.util.PdfGenerator;
import com.dentacloud.app.util.PdfGenerator.Row;

import java.io.File;
import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.ExecutorService;

import javax.inject.Inject;

import dagger.hilt.android.lifecycle.HiltViewModel;

@HiltViewModel
public class InvoiceViewModel extends ViewModel {
    private final BillingRepository billing;
    private final PatientRepository patients;
    private final SessionStore session;
    private final ExecutorService io;
    private final MutableLiveData<String> message = new MutableLiveData<>();
    private final MutableLiveData<File> pdf = new MutableLiveData<>();

    @Inject
    public InvoiceViewModel(BillingRepository billing, PatientRepository patients, SessionStore session, ExecutorService io) {
        this.billing = billing;
        this.patients = patients;
        this.session = session;
        this.io = io;
    }

    public LiveData<InvoiceEntity> invoice(String id) { return billing.invoice(id); }
    public LiveData<List<InvoiceLineEntity>> lines(String id) { return billing.lines(id); }
    public LiveData<List<PaymentEntryEntity>> payments(String id) { return billing.payments(id); }
    public LiveData<String> message() { return message; }
    public LiveData<File> pdf() { return pdf; }
    public void pdfShown() { pdf.setValue(null); }
    public void messageShown() { message.setValue(null); }
    public boolean canRefund() { return session.can("invoice.refund"); }

    public void record(String invoiceId, String kind, String mode, long amountPaise, String reference) {
        billing.record(invoiceId, kind, mode, amountPaise, reference.isBlank() ? null : reference.trim(),
                r -> message.postValue(r.error() != null ? r.error() : kind.equals(PaymentEntryEntity.REFUND) ? "Refund recorded" : "Payment recorded"));
    }

    /** Draws the receipt off the main thread; the file arrives through pdf(). */
    public void receipt(Context app, InvoiceEntity inv, List<InvoiceLineEntity> lines, List<PaymentEntryEntity> payments) {
        String clinic = session.clinicName();
        patients.load(inv.patientId, (PatientEntity p) -> io.execute(() -> {
            List<Row> rows = new ArrayList<>();
            rows.add(Row.of("Patient: " + (p == null ? "" : p.fullName + " (" + p.patientNo + ")")));
            rows.add(Row.of("Date: " + Dates.dayTime(inv.issuedAt)));
            rows.add(Row.of(""));
            for (InvoiceLineEntity l : lines) rows.add(Row.money(l.qty + " x " + l.description, l.amountPaise * l.qty, false));
            rows.add(Row.of(""));
            rows.add(Row.money("Subtotal", inv.subtotalPaise, false));
            if (inv.discountPaise > 0) rows.add(Row.money("Discount", -inv.discountPaise, false));
            if (inv.taxPaise > 0) rows.add(Row.money("Tax", inv.taxPaise, false));
            rows.add(Row.money("Total", inv.totalPaise, true));
            long paid = 0;
            for (PaymentEntryEntity pe : payments) {
                boolean refund = PaymentEntryEntity.REFUND.equals(pe.kind);
                paid += refund ? -pe.amountPaise : pe.amountPaise;
                rows.add(Row.money((refund ? "Refund " : "Paid ") + pe.mode + " · " + Dates.dayTime(pe.recordedAt),
                        refund ? -pe.amountPaise : pe.amountPaise, false));
            }
            rows.add(Row.money("Balance due", inv.totalPaise - paid, true));
            try {
                pdf.postValue(PdfGenerator.write(app, "receipt-" + inv.invoiceNo + ".pdf", clinic, null,
                        "Receipt " + inv.invoiceNo, rows, "Thank you. This receipt was generated by DentaCloud."));
            } catch (IOException e) {
                message.postValue("Could not create the PDF");
            }
        }));
    }
}
